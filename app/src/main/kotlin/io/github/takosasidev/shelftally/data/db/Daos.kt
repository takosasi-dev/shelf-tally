@Dao
interface ShoppingListDao {
    @Query("SELECT * FROM ShoppingListEntry ORDER BY isChecked, addedAt, id")
    fun observeAll(): Flow<List<ShoppingListEntryEntity>>

    @Query("SELECT * FROM ShoppingListEntry ORDER BY isChecked, addedAt, id")
    suspend fun getAll(): List<ShoppingListEntryEntity>

    @Insert
    suspend fun insert(entry: ShoppingListEntryEntity): Long

    @Insert
    suspend fun insertAll(entries: List<ShoppingListEntryEntity>)

    @Query("UPDATE ShoppingListEntry SET isChecked = :checked WHERE id = :id")
    suspend fun setChecked(id: Long, checked: Boolean)

    @Query("DELETE FROM ShoppingListEntry WHERE id = :id")
    suspend fun deleteById(id: Long)

    @Query("DELETE FROM ShoppingListEntry WHERE isChecked = 1")
    suspend fun deleteChecked()

    /** 在庫が戻った品目の、自動で足した未購入の行を片付ける。手動で足した行は残す。 */
    @Query("DELETE FROM ShoppingListEntry WHERE itemId = :itemId AND isAutoGenerated = 1 AND isChecked = 0")
    suspend fun deleteOpenAutoFor(itemId: Long)

    @Query("DELETE FROM ShoppingListEntry")
    suspend fun deleteAll()
}

