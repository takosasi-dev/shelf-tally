// 集計と絞り込みは :core の Kotlin 側で行うので、DAO は素直な取り出しと書き込みだけを持つ。
// 家庭の消耗品の数(多くて数百)なら、全件を読んでメモリの上で畳むほうが単純で速い。
package io.github.takosasidev.shelftally.data.db

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.Query
import androidx.room.Update
import androidx.room.Upsert
import kotlinx.coroutines.flow.Flow

@Dao
interface ItemDao {
    @Query("SELECT * FROM Item ORDER BY name")
    fun observeAll(): Flow<List<ItemEntity>>

    @Query("SELECT * FROM Item ORDER BY name")
    suspend fun getAll(): List<ItemEntity>

    @Query("SELECT * FROM Item WHERE id = :id")
    suspend fun getById(id: Long): ItemEntity?

    @Insert
    suspend fun insert(item: ItemEntity): Long

    @Insert
    suspend fun insertAll(items: List<ItemEntity>)

    @Update
    suspend fun update(item: ItemEntity)

    @Query("DELETE FROM Item WHERE id = :id")
    suspend fun deleteById(id: Long)

    @Query("DELETE FROM Item")
    suspend fun deleteAll()
}

@Dao
interface CategoryDao {
    @Query("SELECT * FROM Category ORDER BY sortOrder, id")
    fun observeAll(): Flow<List<CategoryEntity>>

    @Query("SELECT * FROM Category ORDER BY sortOrder, id")
    suspend fun getAll(): List<CategoryEntity>

    @Insert
    suspend fun insert(category: CategoryEntity): Long

    @Insert
    suspend fun insertAll(categories: List<CategoryEntity>)

    // REPLACE は使わない。行を消して入れ直すので、品目の categoryId が外部キーで null にされてしまう
    @Update
    suspend fun update(category: CategoryEntity)

    @Update
    suspend fun updateAll(categories: List<CategoryEntity>)

    @Query("DELETE FROM Category WHERE id = :id")
    suspend fun deleteById(id: Long)

    @Query("DELETE FROM Category")
    suspend fun deleteAll()
}

