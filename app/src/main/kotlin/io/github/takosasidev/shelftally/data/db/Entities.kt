// Room の表。表の名前と列の名前は要件定義書 §4 のとおり(後の拡張が `ALTER TABLE Item ...` で列を足す)。
// 中身の型は :core のモデルと 1 対 1。計算は :core のモデルで行い、ここは保存の形だけを持つ。
package io.github.takosasidev.shelftally.data.db

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import androidx.room.TypeConverter
import io.github.takosasidev.shelftally.core.model.AppSettings
import io.github.takosasidev.shelftally.core.model.Category
import io.github.takosasidev.shelftally.core.model.ChangeType
import io.github.takosasidev.shelftally.core.model.ConsumptionLog
import io.github.takosasidev.shelftally.core.model.DarkModeMode
import io.github.takosasidev.shelftally.core.model.Item
import io.github.takosasidev.shelftally.core.model.ShoppingListEntry
import io.github.takosasidev.shelftally.core.model.ThemeColorMode
import io.github.takosasidev.shelftally.core.model.ViewMode
import java.time.Instant
import java.time.LocalDate

/**
 * 日付の保存の形は収支管理アプリと同じ。LocalDate は ISO の文字("2026-11-25"。辞書順 = 日付順)、
 * Instant は epoch ミリ秒。あちらは列を String / Long にして手で変換しているが、
 * こちらは §4 の列の名前を保つために TypeConverter にした。拡張で足す表もこれを使い回す。
 */
class Converters {
    @TypeConverter
    fun localDateToText(value: LocalDate?): String? = value?.toString()

    @TypeConverter
    fun textToLocalDate(value: String?): LocalDate? = value?.let { runCatching { LocalDate.parse(it) }.getOrNull() }

    @TypeConverter
    fun instantToMillis(value: Instant?): Long? = value?.toEpochMilli()

    @TypeConverter
    fun millisToInstant(value: Long?): Instant? = value?.let(Instant::ofEpochMilli)
}

@Entity(tableName = "Category")
data class CategoryEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val name: String,
    val colorArgb: Int,
    val sortOrder: Int,
)

@Entity(
    tableName = "Item",
    // カテゴリを消したら、その品目は未分類(null)に移る
    foreignKeys = [
        ForeignKey(
            entity = CategoryEntity::class,
            parentColumns = ["id"],
            childColumns = ["categoryId"],
            onDelete = ForeignKey.SET_NULL,
        ),
    ],
    indices = [Index("categoryId"), Index("barcodeValue")],
)
data class ItemEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val name: String,
    val barcodeValue: String?,
    val categoryId: Long?,
    val locationTag: String?,
    val currentQuantity: Double,
    val unit: String,
    val lowStockThreshold: Double,
    val expiryDate: LocalDate?,
    val photoUri: String?,
    val recurringPurchaseIntervalDays: Int?,
    val lastRecurringNotifiedAt: Instant?,
    val iconKey: String?,
    val isArchived: Boolean,
    val createdAt: Instant,
)

@Entity(
    tableName = "ConsumptionLog",
    // 品目を消したら履歴も消す(FR-27)
    foreignKeys = [
        ForeignKey(
            entity = ItemEntity::class,
            parentColumns = ["id"],
            childColumns = ["itemId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("itemId")],
)
data class ConsumptionLogEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val itemId: Long,
    /** Room は enum を名前の文字で保存する。 */
    val changeType: ChangeType,
    val changeAmount: Double,
    val price: Int?,
    val recordedAt: Instant,
)

@Entity(
    tableName = "ShoppingListEntry",
    foreignKeys = [
        ForeignKey(
            entity = ItemEntity::class,
            parentColumns = ["id"],
            childColumns = ["itemId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("itemId")],
)
data class ShoppingListEntryEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0L,
    val itemId: Long?,
    val label: String,
    val isAutoGenerated: Boolean,
    val isChecked: Boolean,
    val addedAt: Instant,
)

/** 設定は 1 行だけ。§4 に無い `id` は、その 1 行を指すための主キー(常に 1)。 */
@Entity(tableName = "AppSettings")
data class AppSettingsEntity(
    @PrimaryKey val id: Int = SINGLE_ID,
    val themeColorMode: ThemeColorMode,
    val manualThemeColor: Int?,
    val darkModeMode: DarkModeMode,
    val defaultViewMode: ViewMode,
    val expiryAlertLeadDays: Int,
    val autoBackupEnabled: Boolean,
    val autoBackupIntervalDays: Int,
    val autoBackupKeepCount: Int,
    val lastAutoBackupAt: Instant?,
    val appLockEnabled: Boolean,
) {
    companion object {
        const val SINGLE_ID = 1
    }
}

fun CategoryEntity.toModel() = Category(id, name, colorArgb, sortOrder)
fun Category.toEntity() = CategoryEntity(id, name, colorArgb, sortOrder)

fun ItemEntity.toModel() = Item(
    id, name, barcodeValue, categoryId, locationTag, currentQuantity, unit, lowStockThreshold, expiryDate,
    photoUri, recurringPurchaseIntervalDays, lastRecurringNotifiedAt, iconKey, isArchived, createdAt,
)

fun Item.toEntity() = ItemEntity(
    id, name, barcodeValue, categoryId, locationTag, currentQuantity, unit, lowStockThreshold, expiryDate,
    photoUri, recurringPurchaseIntervalDays, lastRecurringNotifiedAt, iconKey, isArchived, createdAt,
)

fun ConsumptionLogEntity.toModel() = ConsumptionLog(id, itemId, changeType, changeAmount, price, recordedAt)
fun ConsumptionLog.toEntity() = ConsumptionLogEntity(id, itemId, changeType, changeAmount, price, recordedAt)

fun ShoppingListEntryEntity.toModel() = ShoppingListEntry(id, itemId, label, isAutoGenerated, isChecked, addedAt)
fun ShoppingListEntry.toEntity() = ShoppingListEntryEntity(id, itemId, label, isAutoGenerated, isChecked, addedAt)

fun AppSettingsEntity.toModel() = AppSettings(
    themeColorMode, manualThemeColor, darkModeMode, defaultViewMode, expiryAlertLeadDays,
    autoBackupEnabled, autoBackupIntervalDays, autoBackupKeepCount, lastAutoBackupAt, appLockEnabled,
)

fun AppSettings.toEntity() = AppSettingsEntity(
    AppSettingsEntity.SINGLE_ID, themeColorMode, manualThemeColor, darkModeMode, defaultViewMode, expiryAlertLeadDays,
    autoBackupEnabled, autoBackupIntervalDays, autoBackupKeepCount, lastAutoBackupAt, appLockEnabled,
)
