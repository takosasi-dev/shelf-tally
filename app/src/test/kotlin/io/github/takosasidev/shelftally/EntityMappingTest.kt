/** 表の形と :core のモデルの行き来で、列を取り違えていないかを確かめる(引数の並びで渡しているため)。 */
class EntityMappingTest {

    private val at = Instant.parse("2026-11-25T01:02:03.456Z")

    @Test
    fun 品目は全部の列が往復する() {
        val item = Item(
            id = 7, name = "しょうゆ", barcodeValue = "4901234567894", categoryId = 2, locationTag = "キッチン",
            currentQuantity = 0.5, unit = "本", lowStockThreshold = 1.0, expiryDate = LocalDate.parse("2027-01-31"),
            photoUri = "a.jpg", recurringPurchaseIntervalDays = 30, lastRecurringNotifiedAt = at.plusSeconds(1),
            iconKey = "food", isArchived = true, createdAt = at,
        )
        assertEquals(item, item.toEntity().toModel())
    }

    @Test
    fun ほかの表も往復する() {
        val category = Category(1, "食品", -123, 4)
        val log = ConsumptionLog(3, 7, ChangeType.RESTOCK, 2.0, 398, at)
        val entry = ShoppingListEntry(5, 7, "しょうゆ", isAutoGenerated = true, isChecked = true, addedAt = at)
        val settings = AppSettings(darkModeMode = DarkModeMode.DARK, manualThemeColor = -1, lastAutoBackupAt = at, appLockEnabled = true)
        assertEquals(category, category.toEntity().toModel())
        assertEquals(log, log.toEntity().toModel())
        assertEquals(entry, entry.toEntity().toModel())
        assertEquals(settings, settings.toEntity().toModel())
    }

    @Test
    fun 日付は_ISO_の文字_日時は_epoch_ミリ秒で保存する() {
        val c = Converters()
        assertEquals("2027-01-31", c.localDateToText(LocalDate.parse("2027-01-31")))
        assertEquals(LocalDate.parse("2027-01-31"), c.textToLocalDate("2027-01-31"))
        assertEquals(at.toEpochMilli(), c.instantToMillis(at))
        assertEquals(at, c.millisToInstant(at.toEpochMilli()))
        assertNull(c.localDateToText(null))
        assertNull(c.textToLocalDate("こわれた値"))
        assertNull(c.millisToInstant(null))
    }
}
