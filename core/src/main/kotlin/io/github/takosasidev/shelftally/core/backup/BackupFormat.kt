// FR-18 バックアップ zip の中身の形式。組み立て・読み取り・検証。zip そのものの読み書きは :app(Zip4j)。
package io.github.takosasidev.shelftally.core.backup

import io.github.takosasidev.shelftally.core.model.AppSettings
import io.github.takosasidev.shelftally.core.model.Category
import io.github.takosasidev.shelftally.core.model.ChangeType
import io.github.takosasidev.shelftally.core.model.ConsumptionLog
import io.github.takosasidev.shelftally.core.model.DarkModeMode
import io.github.takosasidev.shelftally.core.model.Item
import io.github.takosasidev.shelftally.core.model.ShoppingListEntry
import io.github.takosasidev.shelftally.core.model.ThemeColorMode
import io.github.takosasidev.shelftally.core.model.ViewMode
import java.io.StringReader
import java.io.StringWriter
import java.time.Instant
import java.time.LocalDate
import java.util.Properties

data class BackupContent(
    val categories: List<Category>,
    val items: List<Item>,
    val logs: List<ConsumptionLog>,
    val shopping: List<ShoppingListEntry>,
    val settings: AppSettings,
    val exportedAt: Instant? = null,
    val appVersionName: String? = null,
    /** zip に実際に入っていた写真の枚数。 */
    val photoCount: Int = 0,
)

/**
 * JSON のライブラリは足さない。`java.util.Properties` と CSV で足り、人が開いて確かめられる。
 *
 * ```
 * manifest.properties   schemaVersion / appVersionName / exportedAt / itemCount / photoCount
 * categories.csv        Category の全列
 * items.csv             Item の全列
 * logs.csv              ConsumptionLog の全列
 * shopping.csv          ShoppingListEntry の全列
 * settings.properties   AppSettings の全項目
 * photos/<名前>.jpg     品目の写真(参照されている分だけ)
 * ```
 */
object BackupFormat {

    const val ENTRY_MANIFEST = "manifest.properties"
    const val ENTRY_CATEGORIES = "categories.csv"
    const val ENTRY_ITEMS = "items.csv"
    const val ENTRY_LOGS = "logs.csv"
    const val ENTRY_SHOPPING = "shopping.csv"
    const val ENTRY_SETTINGS = "settings.properties"
    const val ENTRY_PHOTOS_DIR = "photos/"

    val TEXT_ENTRIES = listOf(ENTRY_MANIFEST, ENTRY_CATEGORIES, ENTRY_ITEMS, ENTRY_LOGS, ENTRY_SHOPPING, ENTRY_SETTINGS)

    const val KEY_SCHEMA_VERSION = "schemaVersion"
    const val KEY_APP_VERSION = "appVersionName"
    const val KEY_EXPORTED_AT = "exportedAt"
    const val KEY_ITEM_COUNT = "itemCount"
    const val KEY_PHOTO_COUNT = "photoCount"

    private val CATEGORY_HEADER = listOf("id", "name", "colorArgb", "sortOrder")
    private val ITEM_HEADER = listOf(
        "id", "name", "barcodeValue", "categoryId", "locationTag", "currentQuantity", "unit",
        "lowStockThreshold", "expiryDate", "photoUri", "recurringPurchaseIntervalDays",
        "lastRecurringNotifiedAt", "iconKey", "isArchived", "createdAt",
    )
    private val LOG_HEADER = listOf("id", "itemId", "changeType", "changeAmount", "price", "recordedAt")
    private val SHOPPING_HEADER = listOf("id", "itemId", "label", "isAutoGenerated", "isChecked", "addedAt")

    // ---- manifest ----------------------------------------------------------

    fun manifest(schemaVersion: Int, appVersionName: String, exportedAt: Instant, itemCount: Int, photoCount: Int): String =
        writeProperties(
            Properties().apply {
                setProperty(KEY_SCHEMA_VERSION, schemaVersion.toString())
                setProperty(KEY_APP_VERSION, appVersionName)
                setProperty(KEY_EXPORTED_AT, exportedAt.toString())
                setProperty(KEY_ITEM_COUNT, itemCount.toString())
                setProperty(KEY_PHOTO_COUNT, photoCount.toString())
            },
            comment = "ShelfTally backup manifest",
        )

    /**
     * 読み込んでよければ null、駄目ならそのまま画面に出せる文。
     * 新しい版のアプリが作った zip は中止する(知らない列を落として上書きしないため)。
     * 古い版の zip は受ける(無い列は未設定として読める)。
     */
    fun validateManifest(manifestText: String?, supportedSchemaVersion: Int): String? {
        if (manifestText == null) {
            return "バックアップファイルに $ENTRY_MANIFEST が入っていません。このアプリのエクスポートで作った zip を選び直してください。"
        }
        val version = readProperties(manifestText).getProperty(KEY_SCHEMA_VERSION)?.trim()?.toIntOrNull()
            ?: return "バックアップファイルの形式が不正です($KEY_SCHEMA_VERSION を読み取れません)。" +
                "このアプリのエクスポートで作った zip を選び直してください。"
        return when {
            version < 1 -> "バックアップファイルの形式が不正です(データ形式 v$version)。読み込みを中止しました。"
            version <= supportedSchemaVersion -> null
            else -> "このバックアップは新しい版のアプリ(データ形式 v$version)で作られています。" +
                "このアプリ(v$supportedSchemaVersion)では読み込めないため中止しました。アプリを更新してからお試しください。"
        }
    }

    fun manifestValue(manifestText: String?, key: String): String? =
        manifestText?.let { readProperties(it).getProperty(key) }

    // ---- CSV ---------------------------------------------------------------

    fun categoriesCsv(rows: List<Category>): String = buildString {
        append(Csv.row(CATEGORY_HEADER))
        rows.forEach { c -> append(Csv.row(listOf(c.id.toString(), c.name, c.colorArgb.toString(), c.sortOrder.toString()))) }
    }

    fun parseCategoriesCsv(text: String): List<Category> = Csv.parseKeyed(text) { get ->
        Category(
            id = get("id").toLongOrNull() ?: return@parseKeyed null,
            name = get("name").ifBlank { return@parseKeyed null },
            colorArgb = get("colorArgb").toIntOrNull() ?: return@parseKeyed null,
            sortOrder = get("sortOrder").toIntOrNull() ?: 0,
        )
    }

    fun itemsCsv(rows: List<Item>): String = buildString {
        append(Csv.row(ITEM_HEADER))
        rows.forEach { i ->
            append(
                Csv.row(
                    listOf(
                        i.id.toString(), i.name, i.barcodeValue, i.categoryId?.toString(), i.locationTag,
                        i.currentQuantity.toString(), i.unit, i.lowStockThreshold.toString(),
                        i.expiryDate?.toString(), i.photoUri, i.recurringPurchaseIntervalDays?.toString(),
                        i.lastRecurringNotifiedAt?.toString(), i.iconKey, i.isArchived.toString(), i.createdAt.toString(),
                    ),
                ),
            )
        }
    }

    fun parseItemsCsv(text: String): List<Item> = Csv.parseKeyed(text) { get ->
        Item(
            id = get("id").toLongOrNull() ?: return@parseKeyed null,
            name = get("name").ifBlank { return@parseKeyed null },
            barcodeValue = get("barcodeValue").ifBlank { null },
            categoryId = get("categoryId").toLongOrNull(),
            locationTag = get("locationTag").ifBlank { null },
            currentQuantity = amount(get("currentQuantity")) ?: return@parseKeyed null,
            unit = get("unit").ifBlank { "個" },
            lowStockThreshold = amount(get("lowStockThreshold")) ?: 0.0,
            expiryDate = runCatching { LocalDate.parse(get("expiryDate")) }.getOrNull(),
            photoUri = get("photoUri").takeIf(::isSafePhotoName),
            recurringPurchaseIntervalDays = get("recurringPurchaseIntervalDays").toIntOrNull()?.takeIf { it > 0 },
            lastRecurringNotifiedAt = instant(get("lastRecurringNotifiedAt")),
            iconKey = get("iconKey").ifBlank { null },
            isArchived = get("isArchived").toBooleanStrictOrNull() ?: false,
            createdAt = instant(get("createdAt")) ?: Instant.EPOCH,
        )
    }

    fun logsCsv(rows: List<ConsumptionLog>): String = buildString {
        append(Csv.row(LOG_HEADER))
        rows.forEach { l ->
            append(
                Csv.row(
                    listOf(
                        l.id.toString(), l.itemId.toString(), l.changeType.name, l.changeAmount.toString(),
                        l.price?.toString(), l.recordedAt.toString(),
                    ),
                ),
            )
        }
    }

    fun parseLogsCsv(text: String): List<ConsumptionLog> = Csv.parseKeyed(text) { get ->
        ConsumptionLog(
            id = get("id").toLongOrNull() ?: return@parseKeyed null,
            itemId = get("itemId").toLongOrNull() ?: return@parseKeyed null,
            changeType = runCatching { ChangeType.valueOf(get("changeType")) }.getOrNull() ?: return@parseKeyed null,
            changeAmount = amount(get("changeAmount")) ?: return@parseKeyed null,
            price = get("price").toIntOrNull()?.takeIf { it >= 0 },
            recordedAt = instant(get("recordedAt")) ?: return@parseKeyed null,
        )
    }

    fun shoppingCsv(rows: List<ShoppingListEntry>): String = buildString {
        append(Csv.row(SHOPPING_HEADER))
        rows.forEach { s ->
            append(
                Csv.row(
                    listOf(
                        s.id.toString(), s.itemId?.toString(), s.label, s.isAutoGenerated.toString(),
                        s.isChecked.toString(), s.addedAt.toString(),
                    ),
                ),
            )
        }
    }

    fun parseShoppingCsv(text: String): List<ShoppingListEntry> = Csv.parseKeyed(text) { get ->
        ShoppingListEntry(
            id = get("id").toLongOrNull() ?: return@parseKeyed null,
            itemId = get("itemId").toLongOrNull(),
            label = get("label").ifBlank { return@parseKeyed null },
            isAutoGenerated = get("isAutoGenerated").toBooleanStrictOrNull() ?: false,
            isChecked = get("isChecked").toBooleanStrictOrNull() ?: false,
            addedAt = instant(get("addedAt")) ?: Instant.EPOCH,
        )
    }

    // ---- settings.properties ----------------------------------------------

    fun settingsProperties(s: AppSettings): String = writeProperties(
        Properties().apply {
            setProperty("themeColorMode", s.themeColorMode.name)
            s.manualThemeColor?.let { setProperty("manualThemeColor", it.toString()) }
            setProperty("darkModeMode", s.darkModeMode.name)
            setProperty("defaultViewMode", s.defaultViewMode.name)
            setProperty("expiryAlertLeadDays", s.expiryAlertLeadDays.toString())
            setProperty("autoBackupEnabled", s.autoBackupEnabled.toString())
            setProperty("autoBackupIntervalDays", s.autoBackupIntervalDays.toString())
            setProperty("autoBackupKeepCount", s.autoBackupKeepCount.toString())
            s.lastAutoBackupAt?.let { setProperty("lastAutoBackupAt", it.toString()) }
            setProperty("appLockEnabled", s.appLockEnabled.toString())
        },
        comment = "ShelfTally settings",
    )

    /** 知らないキーや欠けたキーは既定値にする。 */
    fun parseSettings(text: String?): AppSettings {
        val d = AppSettings()
        val p = readProperties(text ?: return d)
        fun str(key: String): String? = p.getProperty(key)?.trim()?.ifBlank { null }
        fun int(key: String, fallback: Int, min: Int): Int = str(key)?.toIntOrNull()?.takeIf { it >= min } ?: fallback
        fun bool(key: String, fallback: Boolean): Boolean = str(key)?.toBooleanStrictOrNull() ?: fallback
        return AppSettings(
            themeColorMode = str("themeColorMode")?.let { runCatching { ThemeColorMode.valueOf(it) }.getOrNull() }
                ?: d.themeColorMode,
            manualThemeColor = str("manualThemeColor")?.toIntOrNull(),
            darkModeMode = str("darkModeMode")?.let { runCatching { DarkModeMode.valueOf(it) }.getOrNull() }
                ?: d.darkModeMode,
            defaultViewMode = str("defaultViewMode")?.let { runCatching { ViewMode.valueOf(it) }.getOrNull() }
                ?: d.defaultViewMode,
            expiryAlertLeadDays = int("expiryAlertLeadDays", d.expiryAlertLeadDays, 0),
            autoBackupEnabled = bool("autoBackupEnabled", d.autoBackupEnabled),
            autoBackupIntervalDays = int("autoBackupIntervalDays", d.autoBackupIntervalDays, 1),
            autoBackupKeepCount = int("autoBackupKeepCount", d.autoBackupKeepCount, 1),
            lastAutoBackupAt = str("lastAutoBackupAt")?.let(::instant),
            appLockEnabled = bool("appLockEnabled", d.appLockEnabled),
        )
    }

    // ---- 検証 --------------------------------------------------------------

    /**
     * 写真の名前として安全か。zip は外から来るファイルなので、`../` などでアプリのフォルダの外を指させない。
     */
    fun isSafePhotoName(name: String): Boolean =
        name.isNotBlank() && name != "." && name != ".." && name.none { it == '/' || it == '\\' || it == '\u0000' }

    /**
     * 復元の前に、表どうしのつながりを直す。DB は外部キーを張っているので、
     * 相手のいない行をそのまま入れると復元の途中で失敗する。
     * - 同じ id の行は最初の 1 つだけ
     * - 無いカテゴリを指す品目は未分類に
     * - 無い品目を指す履歴は捨てる。買い物リストの行は一時の買い物(itemId = null)として残す
     * - 同じ品目を指す買い物リストの行は最初の 1 つだけ
     */
    fun sanitize(c: BackupContent): BackupContent {
        val categories = c.categories.distinctBy { it.id }
        val categoryIds = categories.map { it.id }.toSet()
        val items = c.items.distinctBy { it.id }
            .map { if (it.categoryId != null && it.categoryId !in categoryIds) it.copy(categoryId = null) else it }
        val itemIds = items.map { it.id }.toSet()
        val listed = mutableSetOf<Long>()
        return c.copy(
            categories = categories,
            items = items,
            logs = c.logs.distinctBy { it.id }.filter { it.itemId in itemIds },
            shopping = c.shopping.distinctBy { it.id }
                .map { if (it.itemId != null && it.itemId !in itemIds) it.copy(itemId = null) else it }
                // 1 つの品目の行は 1 つだけ(FR-04 の重複なし)。2 つあると購入完了の画面で同じ品目が並んで落ちる
                .filter { it.itemId == null || listed.add(it.itemId) },
        )
    }

    // ---- 共通 --------------------------------------------------------------

    private fun amount(raw: String): Double? = raw.trim().toDoubleOrNull()?.takeIf { it.isFinite() && it >= 0.0 }

    private fun instant(raw: String): Instant? = runCatching { Instant.parse(raw.trim()) }.getOrNull()

    private fun writeProperties(props: Properties, comment: String): String =
        StringWriter().use { w ->
            props.store(w, comment)
            w.toString()
        }

    private fun readProperties(text: String): Properties =
        Properties().apply { StringReader(text).use { load(it) } }
}
