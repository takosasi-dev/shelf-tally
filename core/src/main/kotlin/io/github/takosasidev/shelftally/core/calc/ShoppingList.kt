// FR-04 / FR-15 買い物リストの行の作り方(重複させない)と、共有するテキスト。
package io.github.takosasidev.shelftally.core.calc

import io.github.takosasidev.shelftally.core.model.Item
import io.github.takosasidev.shelftally.core.model.ShoppingListEntry
import java.time.Instant

object ShoppingList {

    /** 同じ品目の行が既にあれば足さない(手動でも自動でも。チェック済みの行も 1 行と数える)。 */
    fun entryFor(item: Item, existing: List<ShoppingListEntry>, auto: Boolean, now: Instant): ShoppingListEntry? {
        if (existing.any { it.itemId == item.id }) return null
        return ShoppingListEntry(itemId = item.id, label = item.name, isAutoGenerated = auto, addedAt = now)
    }

    /** 在庫に無い一時の買い物。空の名前は足さない。 */
    fun freeEntry(label: String, now: Instant): ShoppingListEntry? {
        val name = label.trim()
        if (name.isEmpty()) return null
        return ShoppingListEntry(itemId = null, label = name, isAutoGenerated = false, addedAt = now)
    }

    /** 共有するテキスト。まだ買っていない行だけ。在庫の品目には残量を添える。 */
    fun shareText(entries: List<ShoppingListEntry>, items: Map<Long, Item>): String {
        val open = entries.filter { !it.isChecked }
        if (open.isEmpty()) return "買い物リストは空です"
        return buildString {
            append("買い物リスト(${open.size}件)\n")
            open.forEach { e ->
                val item = e.itemId?.let(items::get)
                append("・").append(item?.name ?: e.label)
                if (item != null) append("(残り ${Format.quantity(item.currentQuantity, item.unit)})")
                append('\n')
            }
        }.trimEnd()
    }
}
