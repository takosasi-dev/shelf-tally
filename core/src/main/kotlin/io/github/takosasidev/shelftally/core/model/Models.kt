// 在庫管理のデータの形。名前と項目は要件定義書 §4 のとおり。
// Room の表(:app の data/db/Entities.kt)と 1 対 1 で、後の拡張(作品台帳)が列を足す前提。
package io.github.takosasidev.shelftally.core.model

import java.time.Instant
import java.time.LocalDate

enum class ChangeType { CONSUME, RESTOCK }
enum class ThemeColorMode { DYNAMIC, MANUAL }
enum class DarkModeMode { SYSTEM, LIGHT, DARK }
enum class ViewMode { LIST, GRID }

data class Item(
    val id: Long = 0L,
    val name: String,
    val barcodeValue: String? = null,
    val categoryId: Long? = null,
    val locationTag: String? = null,
    val currentQuantity: Double = 0.0,
    val unit: String = "個",
    val lowStockThreshold: Double = 0.0,
    val expiryDate: LocalDate? = null,
    /** 写真のファイル名(アプリ内の photos フォルダの中)。別の端末へ復元しても通じるよう、絶対パスは入れない。 */
    val photoUri: String? = null,
    val recurringPurchaseIntervalDays: Int? = null,
    val lastRecurringNotifiedAt: Instant? = null,
    val iconKey: String? = null,
    val isArchived: Boolean = false,
    val createdAt: Instant,
)

data class Category(
    val id: Long = 0L,
    val name: String,
    val colorArgb: Int,
    val sortOrder: Int,
)

data class ConsumptionLog(
    val id: Long = 0L,
    val itemId: Long,
    val changeType: ChangeType,
    /** 増減の量。向きは [changeType] で持ち、ここは常に 0 以上。 */
    val changeAmount: Double,
    /** 補充のときに払った金額(円)。任意。 */
    val price: Int? = null,
    val recordedAt: Instant,
)

data class ShoppingListEntry(
    val id: Long = 0L,
    /** 在庫の品目に結び付く行。在庫に無い一時の買い物は null。 */
    val itemId: Long? = null,
    val label: String,
    val isAutoGenerated: Boolean,
    val isChecked: Boolean = false,
    val addedAt: Instant,
)

data class AppSettings(
    val themeColorMode: ThemeColorMode = ThemeColorMode.DYNAMIC,
    val manualThemeColor: Int? = null,
    val darkModeMode: DarkModeMode = DarkModeMode.SYSTEM,
    val defaultViewMode: ViewMode = ViewMode.LIST,
    val expiryAlertLeadDays: Int = 3,
    val autoBackupEnabled: Boolean = false,
    val autoBackupIntervalDays: Int = 7,
    val autoBackupKeepCount: Int = 5,
    val lastAutoBackupAt: Instant? = null,
    val appLockEnabled: Boolean = false,
)
