package io.github.takosasidev.shelftally.core

import io.github.takosasidev.shelftally.core.backup.BackupContent
import io.github.takosasidev.shelftally.core.backup.BackupFormat
import io.github.takosasidev.shelftally.core.backup.Csv
import io.github.takosasidev.shelftally.core.model.AppSettings
import io.github.takosasidev.shelftally.core.model.Category
import io.github.takosasidev.shelftally.core.model.ChangeType
import io.github.takosasidev.shelftally.core.model.ConsumptionLog
import io.github.takosasidev.shelftally.core.model.DarkModeMode
import io.github.takosasidev.shelftally.core.model.Item
import io.github.takosasidev.shelftally.core.model.ShoppingListEntry
import io.github.takosasidev.shelftally.core.model.ThemeColorMode
import io.github.takosasidev.shelftally.core.model.ViewMode
import java.time.Instant
import java.time.LocalDate
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNotNull
import kotlin.test.assertNull
import kotlin.test.assertTrue

class BackupFormatTest {

    private val categories = listOf(
        Category(id = 1, name = "日用品", colorArgb = 0xFF3F51B5.toInt(), sortOrder = 0),
        Category(id = 2, name = "食品, 調味料", colorArgb = -1, sortOrder = 1),
    )

    private val full = Item(
        id = 7,
        name = "しょうゆ \"特選\"\n1L",
        barcodeValue = "4901234567894",
        categoryId = 2,
        locationTag = " キッチン ",
        currentQuantity = 0.3,
        unit = "本",
        lowStockThreshold = 1.0,
        expiryDate = LocalDate.parse("2027-01-31"),
        photoUri = "0b7c.jpg",
        recurringPurchaseIntervalDays = 30,
        lastRecurringNotifiedAt = Instant.parse("2026-11-20T00:00:00Z"),
        iconKey = "food",
        isArchived = true,
        createdAt = Instant.parse("2026-10-01T12:34:56.789Z"),
    )
    private val minimal = Item(id = 8, name = "電池", createdAt = T0)

    private val logs = listOf(
        ConsumptionLog(id = 1, itemId = 7, changeType = ChangeType.CONSUME, changeAmount = 0.1, recordedAt = T0),
        ConsumptionLog(id = 2, itemId = 7, changeType = ChangeType.RESTOCK, changeAmount = 2.0, price = 398, recordedAt = T0.plusSeconds(60)),
    )

    private val shopping = listOf(
        ShoppingListEntry(id = 1, itemId = 7, label = "しょうゆ", isAutoGenerated = true, addedAt = T0),
        ShoppingListEntry(id = 2, itemId = null, label = "お菓子", isAutoGenerated = false, isChecked = true, addedAt = T0),
    )

    @Test
    fun `全部の列が書いて読んで元に戻る`() {
        assertEquals(categories, BackupFormat.parseCategoriesCsv(BackupFormat.categoriesCsv(categories)))
        assertEquals(listOf(full, minimal), BackupFormat.parseItemsCsv(BackupFormat.itemsCsv(listOf(full, minimal))))
        assertEquals(logs, BackupFormat.parseLogsCsv(BackupFormat.logsCsv(logs)))
        assertEquals(shopping, BackupFormat.parseShoppingCsv(BackupFormat.shoppingCsv(shopping)))
    }

    @Test
    fun `設定が書いて読んで元に戻る`() {
        val s = AppSettings(
            themeColorMode = ThemeColorMode.MANUAL,
            manualThemeColor = 0xFF00796B.toInt(),
            darkModeMode = DarkModeMode.DARK,
            defaultViewMode = ViewMode.GRID,
            expiryAlertLeadDays = 0,
            autoBackupEnabled = true,
            autoBackupIntervalDays = 1,
            autoBackupKeepCount = 3,
            lastAutoBackupAt = T0,
            appLockEnabled = true,
        )
        assertEquals(s, BackupFormat.parseSettings(BackupFormat.settingsProperties(s)))
        assertEquals(AppSettings(), BackupFormat.parseSettings(BackupFormat.settingsProperties(AppSettings())))
    }

    @Test
    fun `設定の知らないキー・壊れた値・範囲の外の値は既定値になる`() {
        val text = "themeColorMode=RAINBOW\nexpiryAlertLeadDays=-2\nautoBackupIntervalDays=0\nappLockEnabled=yes\nfuture=1\n"
        assertEquals(AppSettings(), BackupFormat.parseSettings(text))
        assertEquals(AppSettings(), BackupFormat.parseSettings(null))
    }

    @Test
    fun `列の順が違っても、後から増えた列があっても、無い列があっても読める`() {
        val text = "name,futureColumn,id,currentQuantity\r\n電池,x,8,2.5\r\n"
        val item = BackupFormat.parseItemsCsv(text).single()
        assertEquals(8L, item.id)
        assertEquals("電池", item.name)
        assertEquals(2.5, item.currentQuantity)
        assertEquals(0.0, item.lowStockThreshold)
        assertNull(item.expiryDate)
        assertFalse(item.isArchived)
    }

    @Test
    fun `読めない行は捨て、ほかの行は読む`() {
        val text = "id,name,currentQuantity\r\nx,名前だけ,1\r\n2,,1\r\n3,負の数,-1\r\n4,よい行,1\r\n\r\n"
        assertEquals(listOf(4L), BackupFormat.parseItemsCsv(text).map { it.id })
        val logText = "id,itemId,changeType,changeAmount,price,recordedAt\r\n1,7,EAT,1,,2026-11-01T00:00:00Z\r\n2,7,CONSUME,1,,いつか\r\n"
        assertTrue(BackupFormat.parseLogsCsv(logText).isEmpty())
        assertTrue(BackupFormat.parseItemsCsv("").isEmpty())
    }

    @Test
    fun `フォルダの外を指す写真の名前は読まない`() {
        val text = "id,name,currentQuantity,photoUri\r\n1,a,1,../../databases/x\r\n2,b,1,ok.jpg\r\n3,c,1,a\\b.jpg\r\n"
        assertEquals(listOf(null, "ok.jpg", null), BackupFormat.parseItemsCsv(text).map { it.photoUri })
        assertTrue(BackupFormat.isSafePhotoName("0b7c.jpg"))
        assertFalse(BackupFormat.isSafePhotoName(".."))
        assertFalse(BackupFormat.isSafePhotoName("photos/a.jpg"))
        assertFalse(BackupFormat.isSafePhotoName(" "))
    }

    @Test
    fun `manifest が無い・読めない・新しい版は中止し、同じ版と古い版は通す`() {
        val now = BackupFormat.manifest(2, "0.1.0", T0, itemCount = 3, photoCount = 1)
        assertNull(BackupFormat.validateManifest(now, supportedSchemaVersion = 2))
        assertNull(BackupFormat.validateManifest(now, supportedSchemaVersion = 3))
        assertNotNull(BackupFormat.validateManifest(now, supportedSchemaVersion = 1))
        assertNotNull(BackupFormat.validateManifest(null, 1))
        assertNotNull(BackupFormat.validateManifest("schemaVersion=abc", 1))
        assertNotNull(BackupFormat.validateManifest("appVersionName=1", 1))
        assertNotNull(BackupFormat.validateManifest("schemaVersion=0", 1))
        assertEquals(T0.toString(), BackupFormat.manifestValue(now, BackupFormat.KEY_EXPORTED_AT))
        assertEquals("1", BackupFormat.manifestValue(now, BackupFormat.KEY_PHOTO_COUNT))
    }

    @Test
    fun `復元の前に、相手のいない行と重複した id を直す`() {
        val content = BackupContent(
            categories = categories + categories.first().copy(name = "重複"),
            items = listOf(full, minimal.copy(categoryId = 99), minimal.copy(name = "重複")),
            logs = logs + ConsumptionLog(id = 3, itemId = 404, changeType = ChangeType.CONSUME, changeAmount = 1.0, recordedAt = T0),
            shopping = shopping + ShoppingListEntry(id = 3, itemId = 404, label = "消えた品目", isAutoGenerated = true, addedAt = T0),
            settings = AppSettings(),
        )
        val clean = BackupFormat.sanitize(content)
        assertEquals(listOf("日用品", "食品, 調味料"), clean.categories.map { it.name })
        assertEquals(listOf(2L, null), clean.items.map { it.categoryId })
        assertEquals(listOf(1L, 2L), clean.logs.map { it.id })
        assertEquals(listOf(7L, null, null), clean.shopping.map { it.itemId })
        assertEquals("消えた品目", clean.shopping.last().label)
    }

    @Test
    fun `同じ品目を指す買い物リストの行は最初の1つだけ残し、一時の買い物は名前が同じでも残す`() {
        val content = BackupContent(
            categories = categories,
            items = listOf(full),
            logs = emptyList(),
            shopping = shopping +
                ShoppingListEntry(id = 3, itemId = 7, label = "しょうゆ(手で足した行)", isAutoGenerated = false, isChecked = true, addedAt = T0) +
                ShoppingListEntry(id = 4, itemId = null, label = "お菓子", isAutoGenerated = false, addedAt = T0),
            settings = AppSettings(),
        )
        val clean = BackupFormat.sanitize(content)
        assertEquals(listOf(1L, 2L, 4L), clean.shopping.map { it.id })
    }

    @Test
    fun `CSV は引用符の中のカンマ・改行・引用符を1つの欄として読む`() {
        val line = Csv.row(listOf("a,b", "c\"d", "e\r\nf", null, " g "))
        assertEquals("\"a,b\",\"c\"\"d\",\"e\r\nf\",,\" g \"\r\n", line)
        assertEquals(listOf(listOf("a,b", "c\"d", "e\r\nf", "", " g ")), Csv.parseRows(line))
        // 改行が LF だけ、最後の改行が無い形も読む
        assertEquals(listOf(listOf("1", "2"), listOf("3", "")), Csv.parseRows("1,2\n3,"))
    }
}
