package io.github.takosasidev.shelftally.core

import io.github.takosasidev.shelftally.core.calc.Expiry
import io.github.takosasidev.shelftally.core.calc.ExpiryStatus
import io.github.takosasidev.shelftally.core.calc.Recurring
import io.github.takosasidev.shelftally.core.model.ShoppingListEntry
import java.time.LocalDate
import java.time.temporal.ChronoUnit
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

class ExpiryTest {

    private val today = LocalDate.parse("2026-11-25")

    @Test
    fun `期限の段階の境目`() {
        assertEquals(ExpiryStatus.NONE, Expiry.status(null, today, 3))
        assertEquals(ExpiryStatus.OK, Expiry.status(today.plusDays(4), today, 3))
        assertEquals(ExpiryStatus.SOON, Expiry.status(today.plusDays(3), today, 3))
        // 期限の日はまだ切れていない
        assertEquals(ExpiryStatus.SOON, Expiry.status(today, today, 3))
        assertEquals(ExpiryStatus.EXPIRED, Expiry.status(today.minusDays(1), today, 3))
        // 0 日前の設定なら、当日だけが「近い」
        assertEquals(ExpiryStatus.OK, Expiry.status(today.plusDays(1), today, 0))
        assertEquals(ExpiryStatus.SOON, Expiry.status(today, today, 0))
    }

    @Test
    fun `期限の表示`() {
        assertEquals("期限まであと3日", Expiry.label(today.plusDays(3), today))
        assertEquals("期限は今日まで", Expiry.label(today, today))
        assertEquals("期限切れ(2日経過)", Expiry.label(today.minusDays(2), today))
    }

    /** 要件定義書 §8: 期限を 3 日後にした品目は、3 日前の設定で通知の対象になる。 */
    @Test
    fun `期限が近い品目と切れた品目を1回だけ通知する`() {
        val soon = item(id = 1).copy(expiryDate = today.plusDays(3))
        val far = item(id = 2).copy(expiryDate = today.plusDays(10))
        val expired = item(id = 3).copy(expiryDate = today.minusDays(1))
        val none = item(id = 4)
        val archived = item(id = 5, archived = true).copy(expiryDate = today)
        val items = listOf(soon, far, expired, none, archived)

        val first = Expiry.toNotify(items, today, 3, emptySet())
        assertEquals(listOf(1L, 3L), first.map { it.id })

        val notified = first.map(Expiry::notifyKey).toSet()
        assertTrue(Expiry.toNotify(items, today.plusDays(1), 3, notified).isEmpty())
    }

    @Test
    fun `期限を書き換えたら新しい期限でまた通知する。古い印は捨てる`() {
        val before = item(id = 1).copy(expiryDate = today)
        val notified = setOf(Expiry.notifyKey(before), "99|2026-01-01")
        val after = before.copy(expiryDate = today.plusDays(2))
        assertEquals(listOf(1L), Expiry.toNotify(listOf(after), today, 3, notified).map { it.id })
        assertTrue(Expiry.pruneKeys(listOf(after), notified).isEmpty())
        assertEquals(setOf(Expiry.notifyKey(before)), Expiry.pruneKeys(listOf(before), notified))
    }

    @Test
    fun `定期購入の次回日は前回の通知から、無ければ登録日から数える`() {
        val base = item().copy(recurringPurchaseIntervalDays = 30)
        assertEquals(T0.plus(30, ChronoUnit.DAYS), Recurring.nextDue(base))
        val notifiedAt = T0.plus(31, ChronoUnit.DAYS)
        assertEquals(notifiedAt.plus(30, ChronoUnit.DAYS), Recurring.nextDue(base.copy(lastRecurringNotifiedAt = notifiedAt)))
        assertNull(Recurring.nextDue(item()))
        assertNull(Recurring.nextDue(item().copy(recurringPurchaseIntervalDays = 0)))
    }

    @Test
    fun `次回日ちょうどから時期。アーカイブ中は対象外`() {
        val base = item().copy(recurringPurchaseIntervalDays = 30)
        val due = T0.plus(30, ChronoUnit.DAYS)
        assertFalse(Recurring.isDue(base, due.minusSeconds(1)))
        assertTrue(Recurring.isDue(base, due))
        assertFalse(Recurring.isDue(base.copy(isArchived = true), due))
    }

    @Test
    fun `買い物リストに未購入で載っている品目は通知しない`() {
        val a = item(id = 1).copy(recurringPurchaseIntervalDays = 7)
        val b = item(id = 2).copy(recurringPurchaseIntervalDays = 7)
        val c = item(id = 3).copy(recurringPurchaseIntervalDays = 7)
        val notYet = item(id = 4).copy(recurringPurchaseIntervalDays = 90)
        val shopping = listOf(
            ShoppingListEntry(itemId = 1, label = "a", isAutoGenerated = false, addedAt = T0),
            // チェック済み(買った)の行は「載っている」に数えない
            ShoppingListEntry(itemId = 2, label = "b", isAutoGenerated = false, isChecked = true, addedAt = T0),
        )
        val plan = Recurring.plan(listOf(a, b, c, notYet), shopping, T0.plus(8, ChronoUnit.DAYS))
        assertEquals(listOf(2L, 3L), plan.notify.map { it.id })
        assertEquals(listOf(1L), plan.suppressed.map { it.id })
    }
}
