class ShoppingListTest {

    @Test
    fun `同じ品目の行があれば、自動でも手動でも足さない`() {
        val soap = item(id = 1, name = "石けん")
        val first = ShoppingList.entryFor(soap, emptyList(), auto = true, now = T0)
        assertNotNull(first)
        assertEquals(1L, first.itemId)
        assertEquals("石けん", first.label)
        assertEquals(true, first.isAutoGenerated)
        assertNull(ShoppingList.entryFor(soap, listOf(first), auto = true, now = T0))
        assertNull(ShoppingList.entryFor(soap, listOf(first), auto = false, now = T0))
        // チェック済みでも 1 行と数える
        assertNull(ShoppingList.entryFor(soap, listOf(first.copy(isChecked = true)), auto = true, now = T0))
        // 別の品目は足せる
        assertNotNull(ShoppingList.entryFor(item(id = 2), listOf(first), auto = true, now = T0))
    }

    @Test
    fun `一時の買い物は名前の前後の空白を取り、空なら足さない`() {
        assertEquals("お菓子", ShoppingList.freeEntry("  お菓子 ", T0)?.label)
        assertNull(ShoppingList.freeEntry("   ", T0))
        assertNull(ShoppingList.freeEntry("お菓子", T0)?.itemId)
    }

    @Test
    fun `共有のテキストは未購入だけ。在庫の品目には残量を添える`() {
        val paper = item(id = 1, name = "トイレットペーパー", qty = 2.0, unit = "ロール")
        val entries = listOf(
            ShoppingListEntry(id = 1, itemId = 1, label = "古い名前", isAutoGenerated = true, addedAt = T0),
            ShoppingListEntry(id = 2, itemId = null, label = "お菓子", isAutoGenerated = false, addedAt = T0),
            ShoppingListEntry(id = 3, itemId = null, label = "牛乳", isAutoGenerated = false, isChecked = true, addedAt = T0),
        )
        assertEquals(
            "買い物リスト(2件)\n・トイレットペーパー(残り 2 ロール)\n・お菓子",
            ShoppingList.shareText(entries, mapOf(1L to paper)),
        )
        assertEquals("買い物リストは空です", ShoppingList.shareText(entries.takeLast(1), emptyMap()))
    }
}

class ItemFilterTest {

    private val today = LocalDate.parse("2026-11-25")
    private val items = listOf(
        item(id = 1, name = "しょうゆ", qty = 1.0, threshold = 1.0).copy(categoryId = 10, locationTag = "キッチン", expiryDate = today.plusDays(2)),
        item(id = 2, name = "洗剤", qty = 5.0, threshold = 1.0).copy(categoryId = 20, locationTag = "洗面所"),
        item(id = 3, name = "みそ", qty = 0.0, threshold = 1.0).copy(categoryId = 10, locationTag = "キッチン", expiryDate = today.minusDays(1)),
        item(id = 4, name = "電池", qty = 8.0, threshold = 2.0).copy(barcodeValue = "4901234567894", expiryDate = today.plusDays(300)),
        item(id = 5, name = "古い洗剤", qty = 1.0, threshold = 0.0, archived = true).copy(categoryId = 20),
    )

    private fun ids(q: ItemQuery) = ItemFilter.apply(items, q, today, 3).map { it.id }

    @Test
    fun `普段の一覧はアーカイブを出さず、名前順`() {
        // 文字コードの順(かな → 漢字)。しょうゆ、みそ、洗剤、電池
        assertEquals(listOf(1L, 3L, 2L, 4L), ids(ItemQuery()))
        assertEquals(listOf(5L), ids(ItemQuery(archived = true)))
    }

    @Test
    fun `品名の一部とバーコードの番号で探せる`() {
        assertEquals(listOf(2L), ids(ItemQuery(text = "洗")))
        assertEquals(listOf(4L), ids(ItemQuery(text = "4901234567894")))
        assertEquals(emptyList(), ids(ItemQuery(text = "無い物")))
    }

    @Test
    fun `カテゴリ・未分類・保管場所で絞る`() {
        assertEquals(listOf(1L, 3L), ids(ItemQuery(categoryId = 10)))
        assertEquals(listOf(4L), ids(ItemQuery(categoryId = ItemFilter.UNCATEGORIZED)))
        assertEquals(listOf(2L), ids(ItemQuery(location = "洗面所")))
    }

    @Test
    fun `残量の段階と期限で絞る`() {
        assertEquals(listOf(1L, 3L), ids(ItemQuery(level = LevelFilter.LOW)))
        assertEquals(listOf(3L), ids(ItemQuery(level = LevelFilter.OUT)))
        // 期限が近い物と切れた物。300 日先は出ない
        assertEquals(listOf(1L, 3L), ids(ItemQuery(expiringOnly = true)))
    }

    @Test
    fun `残量順は切れ・少ない・十分の順、期限順は期限なしが最後`() {
        assertEquals(listOf(3L, 1L, 2L, 4L), ids(ItemQuery(sort = ItemSort.QUANTITY)))
        assertEquals(listOf(3L, 1L, 4L, 2L), ids(ItemQuery(sort = ItemSort.EXPIRY)))
    }

    @Test
    fun `保管場所の候補はよく使う順で、空は出さない`() {
        assertEquals(listOf("キッチン", "洗面所"), ItemFilter.locations(items + item(id = 9).copy(locationTag = "  ")))
    }
}

class StatsTest {

    private val zone = ZoneOffset.UTC
    private val items = listOf(
        item(id = 1, name = "しょうゆ").copy(categoryId = 10),
        item(id = 2, name = "みそ").copy(categoryId = 10),
        item(id = 3, name = "洗剤").copy(categoryId = 20),
        item(id = 4, name = "電池"),
    )

    // T0 は 2026-11-01。day = 30 は 12 月 1 日
    private val logs = listOf(
        log(ChangeType.CONSUME, 1.0, 0, itemId = 1),
        log(ChangeType.CONSUME, 1.0, 1, itemId = 2),
        log(ChangeType.CONSUME, 1.0, 2, itemId = 3),
        log(ChangeType.CONSUME, 1.0, 3, itemId = 4),
        log(ChangeType.CONSUME, 1.0, 4, itemId = 4),
        log(ChangeType.CONSUME, 1.0, 5, itemId = 4),
        log(ChangeType.RESTOCK, 2.0, 6, itemId = 1, price = 300),
        log(ChangeType.RESTOCK, 2.0, 16, itemId = 1, price = 320),
        log(ChangeType.RESTOCK, 1.0, 7, itemId = 3),
        log(ChangeType.RESTOCK, 1.0, 30, itemId = 3, price = 500),
        // 消した品目の履歴(品目が無い)
        log(ChangeType.CONSUME, 1.0, 1, itemId = 99),
    )

    @Test
    fun `カテゴリ別の消費の回数は多い順。未分類も1つの組`() {
        val result = Stats.consumptionByCategory(logs, items, T0)
        assertEquals(listOf<Long?>(null, 10L, 20L), result.map { it.categoryId })
        assertEquals(listOf(3, 2, 1), result.map { it.count })
        // 期間より前の記録は数えない
        assertEquals(listOf(2), Stats.consumptionByCategory(logs, items, T0.plusSeconds(4 * 86_400)).map { it.count })
    }

    @Test
    fun `月の支出は価格を入れた補充だけを足す`() {
        assertEquals(620, Stats.monthlySpend(logs, YearMonth.of(2026, 11), zone))
        assertEquals(500, Stats.monthlySpend(logs, YearMonth.of(2026, 12), zone))
        assertEquals(0, Stats.monthlySpend(logs, YearMonth.of(2026, 10), zone))
        assertEquals(
            listOf(YearMonth.of(2026, 10) to 0, YearMonth.of(2026, 11) to 620, YearMonth.of(2026, 12) to 500),
            Stats.spendByMonth(logs, YearMonth.of(2026, 12), 3, zone),
        )
    }

    @Test
    fun `よく買う品目は補充の回数順。同数は名前順`() {
        val top = Stats.topPurchased(logs, items)
        assertEquals(listOf("しょうゆ", "洗剤"), top.map { it.item.name })
        assertEquals(listOf(2, 2), top.map { it.count })
        assertEquals(listOf(620, 500), top.map { it.totalPrice })
        assertEquals(1, Stats.topPurchased(logs, items, limit = 1).size)
    }

    @Test
    fun `価格の推移は価格のある補充だけ、古い順`() {
        val history = Stats.priceHistory(logs.filter { it.itemId == 1L }.reversed(), zone)
        assertEquals(listOf(300, 320), history.map { it.price })
        assertEquals(LocalDate.parse("2026-11-07"), history.first().date)
    }

    @Test
    fun `購入の頻度は補充の間隔の平均。1回だけなら出さない`() {
        assertEquals(10.0, Stats.averagePurchaseIntervalDays(logs.filter { it.itemId == 1L }))
        assertNull(Stats.averagePurchaseIntervalDays(logs.filter { it.itemId == 4L }))
    }
}
